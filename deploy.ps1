param(
  [int]$Port = 0,
  [switch]$NoBuild
)

# Native docker commands write progress to stderr; keep them informational and
# check $LASTEXITCODE explicitly instead of turning stderr into a terminating
# error (Windows PowerShell 5.1 would otherwise abort on the first progress line).
$ErrorActionPreference = "Continue"
$PSNativeCommandUseErrorActionPreference = $false
Set-Location -LiteralPath $PSScriptRoot

function New-RandomPassword {
  $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
  try {
    $bytes = New-Object byte[] 24
    $rng.GetBytes($bytes)
    return [Convert]::ToBase64String($bytes).TrimEnd("=").Replace("+", "-").Replace("/", "_")
  } finally {
    $rng.Dispose()
  }
}

function Read-EnvValue([string]$Key) {
  if (-not (Test-Path -LiteralPath ".env")) { return "" }
  foreach ($line in Get-Content -LiteralPath ".env" -Encoding UTF8) {
    if ($line -match "^$([regex]::Escape($Key))=(.*)$") { return $Matches[1] }
  }
  return ""
}

function Write-EnvLines([string[]]$Lines) {
  $encoding = New-Object System.Text.UTF8Encoding($false)
  $content = ($Lines -join "`n") + "`n"
  [IO.File]::WriteAllText((Join-Path (Get-Location) ".env"), $content, $encoding)
}

function Set-EnvValue([string]$Key, [string]$Value) {
  $lines = @()
  if (Test-Path -LiteralPath ".env") { $lines = @(Get-Content -LiteralPath ".env" -Encoding UTF8) }
  $found = $false
  $output = @()
  foreach ($line in $lines) {
    if ($line -match "^$([regex]::Escape($Key))=") {
      $output += "$Key=$Value"
      $found = $true
    } else {
      $output += $line
    }
  }
  if (-not $found) { $output += "$Key=$Value" }
  Write-EnvLines $output
}

function Set-EnvDefault([string]$Key, [string]$Value) {
  if ([string]::IsNullOrWhiteSpace((Read-EnvValue $Key))) {
    Set-EnvValue $Key $Value
  }
}

function Test-PortValue([int]$Value) {
  return ($Value -ge 1 -and $Value -le 65535)
}

$AppPort = 18000
$AppPortArg = ($Port -gt 0)
if ($AppPortArg) { $AppPort = $Port }

if (Test-Path -LiteralPath ".env") {
  $raw = Read-EnvValue "PANEL_PORT"
  if ($raw) {
    if ($raw -notmatch '^\d+$') {
      Write-Host "PANEL_PORT 无效：$raw" -ForegroundColor Red
      exit 1
    }
    if (-not $AppPortArg) { $AppPort = [int]$raw }
  }
}

if (-not (Test-PortValue $AppPort)) {
  Write-Host "面板端口无效：$AppPort（应为 1-65535）" -ForegroundColor Red
  exit 1
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Host "未找到 docker，请先安装 Docker Desktop。" -ForegroundColor Red
  exit 1
}
docker compose version *> $null
if ($LASTEXITCODE -ne 0) {
  Write-Host "未找到 docker compose 插件，请升级 Docker Desktop。" -ForegroundColor Red
  exit 1
}

if (-not (Test-Path -LiteralPath ".env")) {
  Write-EnvLines @(
    "# Generated by deploy.ps1",
    "ADMIN_PASSWORD=$(New-RandomPassword)",
    "SESSION_SECRET=",
    "PANEL_PORT=$AppPort",
    "HARES_STATE_MAX_MB=16",
    "HARES_ASSET_MAX_MB=16",
    "TZ=Asia/Shanghai"
  )
  Write-Host "已生成 .env（包含随机管理员密码）。"
}

if ([string]::IsNullOrWhiteSpace((Read-EnvValue "ADMIN_PASSWORD"))) {
  Set-EnvValue "ADMIN_PASSWORD" (New-RandomPassword)
  Write-Host "已为 .env 生成随机管理员密码。"
}

if ($AppPortArg) { Set-EnvValue "PANEL_PORT" "$AppPort" } else { Set-EnvDefault "PANEL_PORT" "$AppPort" }
Set-EnvDefault "HARES_STATE_MAX_MB" "16"
Set-EnvDefault "HARES_ASSET_MAX_MB" "16"

$PanelPortValue = Read-EnvValue "PANEL_PORT"
if (-not $PanelPortValue) { $PanelPortValue = "18000" }
if ($PanelPortValue -notmatch '^\d+$' -or -not (Test-PortValue ([int]$PanelPortValue))) {
  Write-Host "PANEL_PORT 无效：$PanelPortValue" -ForegroundColor Red
  exit 1
}

Write-Host ""
Write-Host "> docker compose -f docker-compose.yml up -d"
$composeArgs = @("up", "-d")
if (-not $NoBuild) { $composeArgs += "--build" }
& docker compose -f docker-compose.yml @composeArgs 2>&1 | ForEach-Object { Write-Host $_ }
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host ""
Write-Host "等待健康检查..."
$status = "unknown"
for ($i = 0; $i -lt 60; $i++) {
  $status = docker inspect --format "{{if .State.Health}}{{.State.Health.Status}}{{else}}running{{end}}" hares-panel 2>$null
  if (-not $status) { $status = "missing" }
  if ($status -eq "healthy" -or $status -eq "running" -or $status -eq "unhealthy") { break }
  if ($status -eq "exited" -or $status -eq "dead") { break }
  Start-Sleep -Seconds 2
}

$adminPassword = Read-EnvValue "ADMIN_PASSWORD"
if (-not $adminPassword) {
  $adminPassword = (docker exec hares-panel cat /data/admin-password 2>$null | Out-String).Trim()
}

Write-Host ""
Write-Host "============================================================"
if ($status -eq "healthy") {
  Write-Host " Hares-Panel 已启动（健康检查通过）"
} else {
  Write-Host " Hares-Panel 容器状态：$status"
  Write-Host " 如未就绪，请查看：docker compose -f docker-compose.yml logs -f hares-panel"
}
Write-Host " 访问地址：http://localhost:$PanelPortValue"
if ($adminPassword) { Write-Host " 管理员密码：$adminPassword" }
Write-Host " 提示：未内置反向代理；如需公网 HTTPS，请用现有 Nginx / Caddy 等反代到该端口。"
Write-Host "============================================================"
