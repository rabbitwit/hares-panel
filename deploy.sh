#!/usr/bin/env bash
# One-command Docker deployment for Linux / macOS / NAS SSH.
#
# Starts only the Node app on a high host port (default 18000). It does not
# bind 80/443 and does not include a reverse proxy; use your existing Nginx /
# Caddy / router if you need public access or TLS.
#
#   ./deploy.sh
#   ./deploy.sh --port 19000
#   ./deploy.sh --no-build
set -euo pipefail

cd "$(dirname "$0")"

APP_PORT="${PANEL_PORT:-18000}"
NO_BUILD=0
APP_PORT_ARG=""

usage() {
  cat <<'EOF'
用法: ./deploy.sh [选项]

只启动面板（HTTP），默认使用高位端口，不占用 80/443，也不包含反向代理。

  --port <端口>    面板宿主机端口，默认 18000
  --no-build       不重新构建镜像
  -h, --help       显示帮助
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --port)
      APP_PORT="${2:-}"
      APP_PORT_ARG="$APP_PORT"
      shift 2
      ;;
    --no-build)
      NO_BUILD=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "未知参数：$1" >&2
      usage
      exit 1
      ;;
  esac
done

validate_port() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

if ! validate_port "$APP_PORT"; then
  echo "面板端口无效：$APP_PORT（应为 1-65535）" >&2
  exit 1
fi

if ! command -v docker >/dev/null 2>&1; then
  echo "未找到 docker，请先安装 Docker Engine / Docker Desktop。" >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "未找到 docker compose 插件，请安装 Docker Compose v2。" >&2
  exit 1
fi

random_password() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 24 | tr -d '\n=' | tr '+/' '-_'
    return
  fi
  head -c 24 /dev/urandom | base64 | tr -d '\n=' | tr '+/' '-_'
}

read_env() {
  grep -E "^$1=" .env 2>/dev/null | head -n 1 | cut -d= -f2- | tr -d '\r' || true
}

set_env() {
  key="$1"
  value="$2"
  if [ ! -f .env ]; then
    : > .env
  fi
  awk -v key="$key" -v value="$value" '
    BEGIN { found = 0 }
    $0 ~ "^" key "=" { print key "=" value; found = 1; next }
    { print }
    END { if (!found) print key "=" value }
  ' .env > .env.tmp
  mv .env.tmp .env
  chmod 600 .env 2>/dev/null || true
}

ensure_env() {
  key="$1"
  value="$2"
  if [ -z "$(read_env "$key")" ]; then
    set_env "$key" "$value"
  fi
}

if [ ! -f .env ]; then
  umask 077
  cat > .env <<EOF
# Generated by deploy.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ')
ADMIN_PASSWORD=$(random_password)
SESSION_SECRET=
PANEL_PORT=$APP_PORT
HARES_STATE_MAX_MB=16
HARES_ASSET_MAX_MB=16
TZ=Asia/Shanghai
EOF
  chmod 600 .env 2>/dev/null || true
  echo "已生成 .env（包含随机管理员密码）。"
fi

if [ -z "$(read_env ADMIN_PASSWORD)" ]; then
  set_env ADMIN_PASSWORD "$(random_password)"
  echo "已为 .env 生成随机管理员密码。"
fi

ensure_env PANEL_PORT "$APP_PORT"
ensure_env HARES_STATE_MAX_MB "16"
ensure_env HARES_ASSET_MAX_MB "16"
if [ -n "$APP_PORT_ARG" ]; then set_env PANEL_PORT "$APP_PORT"; fi

PANEL_PORT_VALUE="$(read_env PANEL_PORT)"
PANEL_PORT_VALUE="${PANEL_PORT_VALUE:-18000}"
if ! validate_port "$PANEL_PORT_VALUE"; then
  echo "PANEL_PORT 无效：$PANEL_PORT_VALUE（应为 1-65535）" >&2
  exit 1
fi

echo
COMPOSE_FILE="docker-compose.yml"
if [ "$PANEL_PORT_VALUE" != "18000" ]; then
  # docker-compose.yml 里的 18000:18000 是给 NAS 面板预填用的字面默认值；
  # 自定义端口时生成一份同目录的覆盖文件，避免改动主文件。
  COMPOSE_FILE=".compose.deploy.yml"
  sed "s|^      - \"18000:18000\"|      - \"$PANEL_PORT_VALUE:18000\"|" docker-compose.yml > "$COMPOSE_FILE"
  if ! grep -q "\"$PANEL_PORT_VALUE:18000\"" "$COMPOSE_FILE"; then
    echo "无法从 docker-compose.yml 生成端口覆盖文件，请手动修改 ports 行。" >&2
    rm -f "$COMPOSE_FILE"
    exit 1
  fi
fi

echo "> docker compose -f $COMPOSE_FILE up -d"
if [ "$NO_BUILD" = 1 ]; then
  docker compose -f "$COMPOSE_FILE" up -d
else
  docker compose -f "$COMPOSE_FILE" up -d --build
fi

echo
echo "等待健康检查..."
STATUS="unknown"
ATTEMPT=0
while [ "$ATTEMPT" -lt 60 ]; do
  STATUS="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}running{{end}}' hares-panel 2>/dev/null || echo missing)"
  if [ "$STATUS" = "healthy" ] || [ "$STATUS" = "running" ]; then
    break
  fi
  if [ "$STATUS" = "unhealthy" ]; then
    break
  fi
  if [ "$STATUS" = "exited" ] || [ "$STATUS" = "dead" ]; then
    break
  fi
  ATTEMPT=$((ATTEMPT + 1))
  sleep 2
done

ADMIN_PASSWORD="$(read_env ADMIN_PASSWORD)"
if [ -z "$ADMIN_PASSWORD" ]; then
  ADMIN_PASSWORD="$(docker exec hares-panel cat /data/admin-password 2>/dev/null | tr -d '\r\n' || true)"
fi

echo
echo "============================================================"
if [ "$STATUS" = "healthy" ]; then
  echo " Hares-Panel 已启动（健康检查通过）"
else
  echo " Hares-Panel 容器状态：$STATUS"
  echo " 如未就绪，请查看：docker compose -f $COMPOSE_FILE logs -f hares-panel"
fi
echo " 访问地址：http://<服务器IP>:$PANEL_PORT_VALUE"
if [ -n "$ADMIN_PASSWORD" ]; then
  echo " 管理员密码：$ADMIN_PASSWORD"
fi
echo " 提示：未内置反向代理；如需公网 HTTPS，请用现有 Nginx / Caddy 等反代到该端口。"
echo "============================================================"
