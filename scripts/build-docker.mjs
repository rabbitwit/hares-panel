/**
 * Builds the SPA plus the self-hosted Node server used by the Docker image.
 *
 * `vite build` emits `dist/`; esbuild bundles the API core and file-backed
 * storage into a single `server-dist/index.mjs`, so the runtime image does not
 * need `node_modules`.
 */
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tempDir = path.join(root, '.build-tmp')
fs.mkdirSync(tempDir, { recursive: true })

const env = {
  ...process.env,
  TEMP: tempDir,
  TMP: tempDir,
  TMPDIR: tempDir,
}

function run(label, script, args) {
  console.log(`\n> ${label}`)
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: root,
    stdio: 'inherit',
    env,
  })
  if (result.error) {
    console.error(result.error)
    process.exit(1)
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1)
  }
}

run('tsc --noEmit', path.join(root, 'node_modules/typescript/bin/tsc'), ['--noEmit'])
run('vite build', path.join(root, 'node_modules/vite/bin/vite.js'), ['build'])

console.log('\n> Node server bundle')
await build({
  entryPoints: [path.join(root, 'server/main.ts')],
  outfile: path.join(root, 'server-dist/index.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  logLevel: 'info',
  banner: {
    js: '// Hares-Panel self-hosted server (generated by scripts/build-docker.mjs)',
  },
})

console.log('\nDocker build output ready: dist/ + server-dist/index.mjs')
