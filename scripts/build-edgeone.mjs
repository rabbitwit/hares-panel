/**
 * Bundles the EdgeOne Makers Node Function entry into the fixed
 * `cloud-functions/api/[[default]].js` route.
 *
 * The Blob SDK stays external because EdgeOne injects its deploy credential
 * into node_modules at build/deploy time.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'cloud-functions', 'api', '[[default]].js')

fs.mkdirSync(path.dirname(outfile), { recursive: true })

await build({
  entryPoints: [path.join(root, 'server', 'edgeone-entry.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  external: ['@edgeone/pages-blob'],
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js: '// Generated by scripts/build-edgeone.mjs. Do not edit by hand.',
  },
})

console.log(
  `EdgeOne function: ${path.relative(root, outfile)} (target node20, build ${process.version})`,
)
